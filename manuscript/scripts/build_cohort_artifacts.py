#!/usr/bin/env python3
"""Build the cohort characteristics table and the Kaplan-Meier figure for Methods.

Reads the audited cohort files in data/derived/ (patient-level, local only) and writes aggregate
artifacts: tables/cohort.tex and figures/cohort_km.pdf. Run from the manuscript directory:
../.venv/bin/python scripts/build_cohort_artifacts.py
"""
from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from lifelines import KaplanMeierFitter  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parents[1]
MONTH = 30.4375
HORIZON = 36

INK, INK2, MUTED, GRID = "#0b0b0b", "#52514e", "#8a8984", "#e6e5e0"
# Cohorts use colours outside the encoder slots 1-5 of the Results figures.
EXTERNAL = "#6250d6"

plt.rcParams.update({
    "font.family": "serif", "font.size": 8, "axes.edgecolor": MUTED, "axes.labelcolor": INK2,
    "xtick.color": INK2, "ytick.color": INK2, "axes.linewidth": 0.6, "xtick.major.width": 0.6,
    "ytick.major.width": 0.6, "legend.frameon": False, "pdf.fonttype": 42,
})


def populations() -> dict[str, pd.DataFrame]:
    lung1 = pd.read_csv(ROOT / "data/derived/lung1/cohort_with_gtv_volume.csv")
    rg = pd.read_csv(ROOT / "data/derived/radiogenomics/cohort_with_gtv_volume.csv")
    pops = {
        "LUNG1": lung1[lung1.region_status == "ready"].copy(),
        "external": rg[rg.region_status == "ready"].copy(),
    }
    for d in pops.values():
        d["months"] = d.os_time_days / MONTH
        # Analytic conventions of the clinical models: legacy T5 -> T4, N4 -> N3.
        d["t_stage"] = d.t_stage.clip(upper=4)
        d["n_stage"] = d.n_stage.clip(upper=3)
    assert [len(d) for d in pops.values()] == [416, 143]
    return pops


def n_pct(count: int, total: int) -> str:
    return f"{count} ({100 * count / total:.0f})"


def med_iqr(x: pd.Series, fmt: str = "{:.0f}") -> str:
    q = x.dropna().quantile([0.25, 0.5, 0.75]).tolist()
    return f"{fmt.format(q[1])} ({fmt.format(q[0])}--{fmt.format(q[2])})"


def column(d: pd.DataFrame) -> dict[str, str]:
    n, t, e = len(d), d.months, d.os_event
    km = KaplanMeierFitter().fit(t, e)
    rev = KaplanMeierFitter().fit(t, 1 - e)
    lo, hi = km.confidence_interval_survival_function_.asof(HORIZON).tolist()
    median_os = km.median_survival_time_
    c = {
        "Patients": str(n),
        "Deaths, overall": n_pct(int(e.sum()), n),
        "Deaths by 36 months": n_pct(int(((t <= HORIZON) & (e == 1)).sum()), n),
        "Censored before 36 months": n_pct(int(((t < HORIZON) & (e == 0)).sum()), n),
        "Median follow-up, months$^{a}$": f"{rev.median_survival_time_:.0f}",
        "Median overall survival, months": "not reached" if np.isinf(median_os) else f"{median_os:.1f}",
        "36-month survival, \\% (95\\% CI)": f"{100 * km.predict(HORIZON):.0f} ({100 * lo:.0f}--{100 * hi:.0f})",
        "Age, years, median (IQR)": med_iqr(d.age),
        "\\quad Age missing": str(int(d.age.isna().sum())),
        "Male sex": n_pct(int((d.sex == "male").sum()), n),
    }
    for k in (1, 2, 3, 4):
        c[f"\\quad T{k}"] = n_pct(int((d.t_stage == k).sum()), n)
    for k in (0, 1, 2, 3):
        c[f"\\quad N{k}"] = n_pct(int((d.n_stage == k).sum()), n)
    for s in ("I", "II", "IIIa", "IIIb"):
        c[f"\\quad {s}"] = n_pct(int((d.overall_stage == s).sum()), n)
    c["\\quad TNM or stage missing"] = n_pct(int(d.overall_stage.isna().sum()), n)
    for label, value in (("Adenocarcinoma", "adenocarcinoma"), ("Squamous cell carcinoma", "squamous cell carcinoma"),
                         ("Large cell carcinoma", "large cell"), ("NSCLC, not otherwise specified", "nos")):
        c[f"\\quad {label}"] = n_pct(int((d.histology == value).sum()), n)
    c["\\quad Histology missing"] = n_pct(int(d.histology.isna().sum()), n)
    vol = d.gtv_volume_cm3
    c["GTV volume, cm$^3$, median (IQR)$^{b}$"] = med_iqr(vol, "{:.1f}") if vol.notna().all() else \
        f"{med_iqr(vol, '{:.1f}')} [{int(vol.notna().sum())}]"
    return c


def cohort_table(pops: dict[str, pd.DataFrame]) -> None:
    cols = {k: column(d) for k, d in pops.items()}
    sections = {"\\quad T1": "T category", "\\quad N0": "N category",
                "\\quad I": "Overall stage$^{c}$", "\\quad Adenocarcinoma": "Histology"}
    body = []
    for key in cols["LUNG1"]:
        if key in sections:
            body.append(f"\\multicolumn{{3}}{{@{{}}l}}{{{sections[key]}}}\\\\")
        body.append(" & ".join([key] + [cols[p][key] for p in pops]) + " \\\\")
    rows = "\n".join(body)
    tex = rf"""% Generated by scripts/build_cohort_artifacts.py from data/derived/; do not edit by hand.
\begin{{table}}[!htbp]
\centering\footnotesize
\caption{{Characteristics of the development and external cohorts. Values are $n$ (\%) unless stated otherwise. NSCLC-Radiogenomics includes only the patients with a tumour segmentation. Survival in LUNG1 is measured from the start of treatment and in NSCLC-Radiogenomics from the date of the input CT. LUNG1 records clinical TNM and NSCLC-Radiogenomics pathological TNM; both were mapped to the same categories (Section~\ref{{sec:clinical}}). IQR, interquartile range; GTV, gross tumour volume.
$^{{a}}$Reverse Kaplan--Meier estimate.
$^{{b}}$From the primary-tumour segmentation.
$^{{c}}$Seventh-edition AJCC stage; in NSCLC-Radiogenomics, the four stage IV (M1) patients are counted as IIIb, the highest LUNG1 category. Legacy LUNG1 codes T5 ($n=2$) and N4 ($n=3$) are counted as T4 and N3.}}
\label{{tab:cohorts}}
\begin{{tabular}}{{@{{}}lrr@{{}}}}
\toprule
 & LUNG1 & NSCLC-Radiogenomics \\
 & development & external \\
\midrule
{rows}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    (OUT / "tables/cohort.tex").write_text(tex)


def km_figure(pops: dict[str, pd.DataFrame]) -> None:
    fig, ax = plt.subplots(figsize=(6.3, 2.9))
    styles = {"LUNG1": (INK2, "-", "LUNG1, development (416)"),
              "external": (EXTERNAL, "-", "NSCLC-Radiogenomics, external (143)")}
    grid = np.arange(0, 61, 12)
    for key, d in pops.items():
        colour, style, label = styles[key]
        km = KaplanMeierFitter().fit(d.months, d.os_event)
        sf = km.survival_function_
        ax.step(sf.index, sf.iloc[:, 0], where="post", color=colour, linestyle=style, linewidth=1.6,
                label=label)
    ax.legend(loc="lower left", bbox_to_anchor=(0.01, 0.02), fontsize=7, handlelength=2.6)
    ax.axvline(HORIZON, color=MUTED, linewidth=0.8, linestyle=(0, (3, 2)))
    ax.text(HORIZON + 0.8, 0.97, "36-month horizon", color=INK2, fontsize=7, va="top")
    ax.set_xlim(0, 60)
    ax.set_ylim(0, 1.02)
    ax.set_xticks(grid)
    ax.set_xlabel("Months")
    ax.set_ylabel("Overall survival")
    ax.grid(axis="y", color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    # Numbers at risk below the axis.
    for i, (key, d) in enumerate(pops.items()):
        y = -0.36 - 0.09 * i
        ax.text(-0.07, y, {"LUNG1": "LUNG1", "external": "External"}[key],
                transform=ax.transAxes, ha="right", va="center", fontsize=6.5, color=INK2)
        for g in grid:
            ax.text(g, y, str(int((d.months >= g).sum())), transform=ax.get_xaxis_transform(),
                    ha="center", va="center", fontsize=6.5, color=INK2)
    ax.text(-0.07, -0.27, "At risk", transform=ax.transAxes, ha="right", va="center",
            fontsize=6.5, color=INK, fontweight="bold")
    fig.subplots_adjust(left=0.14, right=0.97, top=0.97, bottom=0.42)
    fig.savefig(OUT / "figures/cohort_km.pdf")
    plt.close(fig)


if __name__ == "__main__":
    p = populations()
    cohort_table(p)
    km_figure(p)
